#!/usr/bin/env node
/*
 * Migration SQLite (sql.js) -> PostgreSQL : genere un script SQL autonome, transactionnel et rejouable.
 * N'ACTIVE RIEN : l'application continue d'utiliser SQLite. Voir docs/MIGRATION-POSTGRES.md.
 *
 *   node scripts/migrate-to-postgres.js [base.db] > catchr.sql
 *   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f catchr.sql
 *
 * - schema cible type (BOOLEAN, DATE, TIMESTAMPTZ, cles etrangeres declarees, contraintes CHECK)
 * - toutes les versions historiques du schema SQLite sont acceptees (colonnes manquantes -> valeurs par defaut)
 * - lignes orphelines ou invalides ecartees ET signalees (stderr + commentaire dans le SQL)
 * - sequences recalees apres import ; tout dans une transaction (BEGIN ... COMMIT)
 */
const fs = require('fs');
const path = require('path');
const initSqlJs = require('sql.js');

const SCHEMA = `
CREATE TABLE pokemon (
  id          INTEGER PRIMARY KEY,
  name        TEXT    NOT NULL UNIQUE,
  catch_rate  SMALLINT NOT NULL CHECK (catch_rate BETWEEN 0 AND 255),
  generation  SMALLINT NOT NULL CHECK (generation BETWEEN 1 AND 9),
  type1       TEXT    NOT NULL DEFAULT 'normal',
  type2       TEXT
);
CREATE TABLE pokeballs (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key           TEXT    NOT NULL UNIQUE,
  name_en       TEXT    NOT NULL,
  name_fr       TEXT    NOT NULL,
  multiplier    NUMERIC(5,2) NOT NULL CHECK (multiplier > 0),
  cost          INTEGER NOT NULL CHECK (cost >= 0),
  condition_key TEXT,
  sort_order    INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE events (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug        TEXT    NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9][a-z0-9-]{0,63}$'),
  name_en     TEXT    NOT NULL,
  name_fr     TEXT    NOT NULL DEFAULT '',
  active      BOOLEAN NOT NULL DEFAULT TRUE,
  sort_order  INTEGER NOT NULL DEFAULT 0,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  starts_at   DATE,
  ends_at     DATE,
  kind        TEXT,
  forecast    BOOLEAN NOT NULL DEFAULT FALSE,
  unverified  BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE event_pokemon (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id    INTEGER NOT NULL REFERENCES events(id) ON DELETE CASCADE,
  pokemon_id  INTEGER NOT NULL REFERENCES pokemon(id),
  UNIQUE (event_id, pokemon_id)
);
CREATE TABLE admin_users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role          TEXT NOT NULL DEFAULT 'manager' CHECK (role IN ('admin', 'manager')),
  created_at    TIMESTAMPTZ
);
CREATE TABLE pokemon_recoil_moves (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dex_number    INTEGER NOT NULL,
  pokemon_name  TEXT    NOT NULL,
  move_name     TEXT    NOT NULL,
  level         SMALLINT NOT NULL,
  recoil_type   TEXT    NOT NULL
);
CREATE INDEX pokemon_name_lower_idx ON pokemon (lower(name));
CREATE INDEX recoil_dex_idx ON pokemon_recoil_moves (dex_number, level);
CREATE INDEX events_recent_idx ON events (COALESCE(starts_at, (created_at AT TIME ZONE 'UTC')::date) DESC, id DESC);
`;

// Ordre d'import (cles etrangeres) et conversion par colonne
const bool = v => (v == null ? null : Number(v) !== 0);
const date = v => (v && /^\d{4}-\d{2}-\d{2}$/.test(String(v)) ? String(v) : null);
const ts = v => (v ? String(v).replace(' ', 'T') + (/[zZ]|[+-]\d\d:?\d\d$/.test(String(v)) ? '' : 'Z') : null);   // SQLite datetime('now') = UTC
const TABLES = [
  { name: 'pokemon', cols: ['id', 'name', 'catch_rate', 'generation', 'type1', 'type2'] },
  { name: 'pokeballs', cols: ['id', 'key', 'name_en', 'name_fr', 'multiplier', 'cost', 'condition_key', 'sort_order'], defaults: { sort_order: 0 } },
  { name: 'events', cols: ['id', 'slug', 'name_en', 'name_fr', 'active', 'sort_order', 'created_at', 'starts_at', 'ends_at', 'kind', 'forecast', 'unverified'],
    conv: { active: bool, forecast: bool, unverified: bool, starts_at: date, ends_at: date, created_at: ts },
    defaults: { name_fr: '', active: 1, sort_order: 0, forecast: 0, unverified: 0 },
    // created_at absent : on laisse le DEFAULT now() de PostgreSQL
    omitNull: ['created_at'] },
  { name: 'event_pokemon', cols: ['id', 'event_id', 'pokemon_id'] },
  { name: 'admin_users', cols: ['id', 'username', 'password_hash', 'role', 'created_at'], conv: { created_at: ts }, defaults: { role: null } },
  { name: 'pokemon_recoil_moves', cols: ['id', 'dex_number', 'pokemon_name', 'move_name', 'level', 'recoil_type'] },
];

const lit = v => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'boolean') return v ? 'TRUE' : 'FALSE';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL';
  return `'${String(v).replace(/'/g, "''")}'`;
};

async function buildSql(dbFile, log = () => {}) {
  const SQL = await initSqlJs();
  const db = new SQL.Database(fs.readFileSync(dbFile));
  const all = (q) => { const r = db.exec(q)[0]; return r ? r.values.map(v => Object.fromEntries(r.columns.map((c, i) => [c, v[i]]))) : []; };
  const has = t => all(`SELECT name FROM sqlite_master WHERE type='table' AND name='${t}'`).length > 0;
  const colsOf = t => all(`PRAGMA table_info(${t})`).map(c => c.name);

  const out = ['-- CatchR : import SQLite -> PostgreSQL (genere par scripts/migrate-to-postgres.js)', 'BEGIN;', SCHEMA.trim(), ''];
  const report = {};
  const pokemonIds = new Set(has('pokemon') ? all('SELECT id FROM pokemon').map(r => r.id) : []);
  const eventIds = new Set(has('events') ? all('SELECT id FROM events').map(r => r.id) : []);
  const firstAdmin = has('admin_users') ? (all('SELECT MIN(id) AS id FROM admin_users')[0] || {}).id : null;

  for (const t of TABLES) {
    if (!has(t.name)) { report[t.name] = { source: 0, imported: 0, skipped: 0 }; log(`table ${t.name} absente : ignoree`); continue; }
    const present = colsOf(t.name);
    const rows = all(`SELECT * FROM ${t.name} ORDER BY ${present.includes('id') ? 'id' : 'rowid'}`);
    let skipped = 0;
    const values = [];
    for (const r of rows) {
      // Lignes rejetees : orphelins (pas de FK declaree cote SQLite pour pokemon_id), slugs non conformes
      if (t.name === 'event_pokemon' && (!eventIds.has(r.event_id) || !pokemonIds.has(r.pokemon_id))) { skipped++; log(`event_pokemon ${r.id} orphelin (event ${r.event_id}, pokemon ${r.pokemon_id}) : ecarte`); continue; }
      if (t.name === 'events' && !/^[a-z0-9][a-z0-9-]{0,63}$/.test(String(r.slug))) { skipped++; log(`evenement ${r.id} : slug non conforme, ecarte`); continue; }
      const cols = [], vals = [];
      for (const c of t.cols) {
        let v = present.includes(c) ? r[c] : (t.defaults && c in t.defaults ? t.defaults[c] : null);
        if (t.name === 'admin_users' && c === 'role' && !present.includes('role')) v = r.id === firstAdmin ? 'admin' : 'manager';   // meme regle que la migration du serveur
        if (t.conv && t.conv[c]) v = t.conv[c](v);
        if (v === null && t.omitNull && t.omitNull.includes(c)) continue;
        cols.push(c); vals.push(lit(v));
      }
      values.push(`INSERT INTO ${t.name} (${cols.join(', ')}) VALUES (${vals.join(', ')});`);
    }
    report[t.name] = { source: rows.length, imported: values.length, skipped };
    out.push(`-- ${t.name} : ${values.length} ligne(s)${skipped ? `, ${skipped} ecartee(s)` : ''}`, ...values, '');
  }
  for (const t of TABLES.filter(x => x.name !== 'pokemon'))
    out.push(`SELECT setval(pg_get_serial_sequence('${t.name}', 'id'), COALESCE((SELECT MAX(id) FROM ${t.name}), 0) + 1, false);`);
  out.push('COMMIT;', '');
  return { sql: out.join('\n'), report };
}

module.exports = { buildSql, SCHEMA };

if (require.main === module) {
  const file = process.argv[2] || process.env.CATCHR_DB_PATH || path.join(__dirname, '..', 'db', 'catchrates.db');
  buildSql(file, m => console.error('[migration] ' + m)).then(({ sql, report }) => {
    process.stdout.write(sql);
    console.error('[migration] bilan : ' + JSON.stringify(report));
  }).catch(e => { console.error(e.message); process.exit(1); });
}
